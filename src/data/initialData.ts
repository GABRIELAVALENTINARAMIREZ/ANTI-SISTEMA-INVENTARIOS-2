export const GAMA_SQL_SCHEMA = `-- =========================================================
-- BASE DE DATOS: gama_db (MySQL 8 / MariaDB - XAMPP)
-- Proyecto: GAMA (FastStock) - Comidas Rápidas
-- Ruta recomendada: C:\\xampp\\htdocs\\gama\\database\\gama_db.sql
-- =========================================================

CREATE DATABASE IF NOT EXISTS gama_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE gama_db;

CREATE TABLE roles (
  id_rol INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  descripcion VARCHAR(255)
) ENGINE=InnoDB;

CREATE TABLE usuarios (
  id_usuario INT AUTO_INCREMENT PRIMARY KEY,
  id_rol INT NOT NULL,
  nombre VARCHAR(120) NOT NULL,
  usuario VARCHAR(60) NOT NULL UNIQUE,
  correo VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  estado ENUM('Activo','Inactivo') DEFAULT 'Activo',
  ultimo_acceso DATETIME NULL,
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES roles(id_rol)
) ENGINE=InnoDB;

CREATE TABLE categorias (
  id_categoria INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  descripcion VARCHAR(255),
  icono VARCHAR(40) DEFAULT 'Package',
  color VARCHAR(20) DEFAULT '#E63946'
) ENGINE=InnoDB;

CREATE TABLE proveedores (
  id_proveedor INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  nit VARCHAR(30) NOT NULL UNIQUE,
  telefono VARCHAR(30),
  correo VARCHAR(120),
  direccion VARCHAR(200),
  estado ENUM('Activo','Inactivo') DEFAULT 'Activo',
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE ubicaciones (
  id_ubicacion INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  tipo ENUM('Ambiente','Refrigerado','Congelado') NOT NULL
) ENGINE=InnoDB;

CREATE TABLE productos (
  id_producto INT AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  imagen VARCHAR(255),
  id_categoria INT NOT NULL,
  id_proveedor INT NOT NULL,
  id_ubicacion INT NULL,
  cantidad DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
  unidad_medida VARCHAR(30) NOT NULL,
  stock_minimo DECIMAL(10,2) NOT NULL DEFAULT 0,
  precio_compra DECIMAL(12,2) NOT NULL DEFAULT 0,
  actualizado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_prod_cat FOREIGN KEY (id_categoria) REFERENCES categorias(id_categoria),
  CONSTRAINT fk_prod_prov FOREIGN KEY (id_proveedor) REFERENCES proveedores(id_proveedor),
  CONSTRAINT fk_prod_ubic FOREIGN KEY (id_ubicacion) REFERENCES ubicaciones(id_ubicacion)
) ENGINE=InnoDB;

CREATE TABLE movimientos (
  id_movimiento INT AUTO_INCREMENT PRIMARY KEY,
  tipo ENUM('entrada','salida') NOT NULL,
  subtipo VARCHAR(60) NOT NULL,
  id_proveedor INT NULL,
  id_usuario INT NOT NULL,
  observacion TEXT,
  total_cop DECIMAL(14,2) NOT NULL DEFAULT 0,
  fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_mov_prov FOREIGN KEY (id_proveedor) REFERENCES proveedores(id_proveedor),
  CONSTRAINT fk_mov_user FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
) ENGINE=InnoDB;

CREATE TABLE detalle_movimientos (
  id_detalle INT AUTO_INCREMENT PRIMARY KEY,
  id_movimiento INT NOT NULL,
  id_producto INT NOT NULL,
  cantidad DECIMAL(10,2) NOT NULL CHECK (cantidad > 0),
  costo_unitario DECIMAL(12,2) NOT NULL DEFAULT 0,
  CONSTRAINT fk_det_mov FOREIGN KEY (id_movimiento) REFERENCES movimientos(id_movimiento) ON DELETE CASCADE,
  CONSTRAINT fk_det_prod FOREIGN KEY (id_producto) REFERENCES productos(id_producto)
) ENGINE=InnoDB;

CREATE TABLE recetas (
  id_receta INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL UNIQUE,
  categoria_menu VARCHAR(80) NOT NULL,
  precio_venta DECIMAL(12,2) NOT NULL DEFAULT 0,
  tiempo_preparacion_min INT DEFAULT 10
) ENGINE=InnoDB;

CREATE TABLE detalle_recetas (
  id_detalle_receta INT AUTO_INCREMENT PRIMARY KEY,
  id_receta INT NOT NULL,
  id_producto INT NOT NULL,
  cantidad DECIMAL(10,2) NOT NULL CHECK (cantidad > 0),
  CONSTRAINT fk_drec_rec FOREIGN KEY (id_receta) REFERENCES recetas(id_receta) ON DELETE CASCADE,
  CONSTRAINT fk_drec_prod FOREIGN KEY (id_producto) REFERENCES productos(id_producto)
) ENGINE=InnoDB;

CREATE TABLE lotes (
  id_lote INT AUTO_INCREMENT PRIMARY KEY,
  numero_lote VARCHAR(50) NOT NULL UNIQUE,
  id_producto INT NOT NULL,
  cantidad DECIMAL(10,2) NOT NULL CHECK (cantidad >= 0),
  fecha_ingreso DATE NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  id_ubicacion INT NULL,
  dado_de_baja TINYINT(1) DEFAULT 0,
  CONSTRAINT fk_lote_prod FOREIGN KEY (id_producto) REFERENCES productos(id_producto),
  CONSTRAINT fk_lote_ubic FOREIGN KEY (id_ubicacion) REFERENCES ubicaciones(id_ubicacion)
) ENGINE=InnoDB;

CREATE TABLE notificaciones (
  id_notificacion INT AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(120) NOT NULL,
  mensaje VARCHAR(255) NOT NULL,
  severidad ENUM('critica','advertencia','info') DEFAULT 'info',
  leida TINYINT(1) DEFAULT 0,
  creada_en DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE auditoria (
  id_auditoria INT AUTO_INCREMENT PRIMARY KEY,
  id_usuario INT NOT NULL,
  accion VARCHAR(80) NOT NULL,
  modulo VARCHAR(60) NOT NULL,
  detalle TEXT,
  fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_aud_user FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
) ENGINE=InnoDB;
`;
